"""Generate the portable C++ schema from the unmodified official catalogue."""
from __future__ import annotations

import argparse
from decimal import Decimal, InvalidOperation
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cpp_string(value: object) -> str:
    return json.dumps("" if value is None else str(value), ensure_ascii=True)


def plain_text(value: str) -> str:
    # The source is LaTeX. Keep meaningful prose without pretending to typeset it.
    text = re.sub(r"\\(?:t|it|bf)\b\s*", "", value)
    text = re.sub(r"\\(?:circuit|nth|texttt|textbf|emph)\{([^{}]*)\}", r"\1", text)
    text = re.sub(r"\\[A-Za-z]+", "", text)
    text = text.replace("{", "").replace("}", "").replace("~", " ")
    return re.sub(r"\s+", " ", text).strip()


def expand_parameter(parameter: dict) -> list[tuple[str, str]]:
    if "prefix" in parameter:
        start = int(parameter.get("start_at", 1))
        return [(f"{parameter['prefix']}{n}", f"{parameter.get('short', '')}{n}" if parameter.get("short") else "")
                for n in range(start, start + int(parameter["count"]))]
    name = parameter["name"]
    if not re.fullmatch(r"[a-zA-Z][a-zA-Z0-9]*", name):
        raise ValueError(f"Unrecognised parameter declaration: {name}")
    return [(name, parameter.get("short", ""))]


def initial_value(parameter: dict, direction: str) -> str:
    """Forge 1.7.1 initializes only numeric-looking input defaults.

    Its QString::toDouble checks the whole string, never a numeric prefix.
    Actual blue-7 defaults are finite plain decimals; text, negative defaults
    and absent defaults deliberately leave an empty cell, just as Forge does.
    """
    value = parameter.get("default")
    if direction != "input" or not isinstance(value, str) or not value or not ("0" <= value[0] <= "9"):
        return ""
    # Decimal accepts underscores and Unicode digits, unlike QString::toDouble.
    # Accept a whole ordinary decimal/exponent before invoking it; a failed Qt
    # conversion returns zero rather than the numeric prefix of a range string.
    if not re.fullmatch(r"[0-9]+(?:\.[0-9]*)?(?:[eE][+-]?[0-9]+)?[ \t\r\n]*", value):
        return "0"
    try:
        number = Decimal(value)
        if not number.is_finite():
            return "0"
        normalized = format(number, "f")
        if "." in normalized:
            normalized = normalized.rstrip("0").rstrip(".")
        return normalized
    except InvalidOperation:
        # Forge ignores toDouble's success flag, whose failed result is zero.
        return "0"


def initial_selection_max(circuit: str, parameter: dict, ordinal: int) -> int:
    essential = int(parameter.get("essential", 0))
    if circuit in ("faderbank", "motorfader"):
        if parameter.get("name") == "select":
            essential = 2
        elif parameter.get("name") == "selectat":
            essential = 1
    if "prefix" in parameter and ordinal >= int(parameter.get("essential_count", parameter["count"])):
        return 0
    return essential


def generate(source: Path, destination: Path) -> None:
    raw = source.read_bytes()
    firmware = json.loads(raw)
    entries = []
    lines = ["// Generated by tools/generate_catalogue.py. Do not edit.",
             f"// Official catalogue SHA-256: {hashlib.sha256(raw).hexdigest()}",
             "#pragma once", "#include <cstddef>", "#include <string>", "namespace androforge {",
             "struct ParameterSchema { const char* name; const char* shortName; const char* type; const char* direction; const char* defaultValue; const char* initialValue; int initialSelectionMax; };",
             "struct CircuitSchema { const char* name; const char* shortName; const ParameterSchema* parameters; std::size_t parameterCount; bool needsMIDI; };",
             f"inline constexpr const char* kFirmware = {cpp_string(firmware['firmware_version'])};"]
    schemas = []
    for index, (name, circuit) in enumerate(sorted(firmware["circuits"].items())):
        # Forge 1.7.1 DroidFirmware::circuitNeedsMIDI; this is not a catalogue
        # category test (firefacecontrol also requires the X7 on MASTER16).
        needs_midi = name in ("midiin", "midiout", "midithrough", "firefacecontrol")
        parameters = []
        schema_parameters = []
        for direction, source_key in (("input", "inputs"), ("output", "outputs")):
            for parameter in circuit[source_key]:
                for ordinal, (expanded_name, alias) in enumerate(expand_parameter(parameter)):
                    initial = initial_value(parameter, direction)
                    selection_max = initial_selection_max(name, parameter, ordinal)
                    parameters.append({"name": expanded_name, "short": alias, "type": parameter["type"],
                                       "direction": direction, "default": parameter.get("default"),
                                       "initialValue": initial, "initialSelectionMax": selection_max,
                                       "description": plain_text(parameter.get("description", ""))})
                    schema_parameters.append("    {" + ", ".join(cpp_string(value) for value in
                        (expanded_name, alias, parameter["type"], direction, parameter.get("default"), initial)) +
                        f", {selection_max}" + "},")
        if schema_parameters:
            lines.append(f"inline constexpr ParameterSchema kParameters{index}[] = {{")
            lines.extend(schema_parameters)
            lines.append("};")
            pointer = f"kParameters{index}"
        else:
            pointer = "nullptr"
        schemas.append("    {" + f"{cpp_string(name)}, {cpp_string(circuit.get('short', ''))}, {pointer}, {len(parameters)}, {str(needs_midi).lower()}" + "},")
        entries.append({"name": name, "short": circuit.get("short", ""), "title": plain_text(circuit.get("title", name)),
                        "category": circuit.get("category", "other"),
                        "description": plain_text(circuit.get("description", "").split("\n\n", 1)[0]),
                        "manualPage": circuit.get("manual", 0), "needsMIDI": needs_midi, "parameters": parameters})
    lines.append("inline constexpr CircuitSchema kCircuits[] = {")
    lines.extend(schemas)
    lines.append("};")
    # ModuleBuilder::allControllers excludes the inferred G8/X7 expanders.
    controllers = sorted(set(firmware["controllers"]) - {"g8", "x7"})
    lines.append("inline constexpr const char* kControllers[] = {" + ", ".join(cpp_string(n) for n in controllers) + "};")
    catalogue_json = json.dumps(entries, ensure_ascii=False, separators=(",", ":"))
    if ')AFJSON"' in catalogue_json:
        raise ValueError("Raw literal delimiter occurs in catalogue")
    # MSVC limits individual string literals. Assemble once from small literals;
    # this also stays within the portable minimum supported by C++ compilers.
    lines.append("inline constexpr const char* kCatalogueJsonChunks[] = {")
    for offset in range(0, len(catalogue_json), 16000):
        lines.append('R"AFJSON(' + catalogue_json[offset:offset + 16000] + ')AFJSON",')
    lines.append("};")
    lines.append("inline const std::string kCatalogueJson = [] {")
    lines.append(f"    std::string result; result.reserve({len(catalogue_json.encode('utf-8'))});")
    lines.append("    for (const char* chunk : kCatalogueJsonChunks) result += chunk;")
    lines.append("    return result;")
    lines.append("}();")
    lines.append("} // namespace androforge")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(entries)} circuits, {sum(len(e['parameters']) for e in entries)} parameters for {firmware['firmware_version']}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "resources/official/circuits.blue-7.json")
    parser.add_argument("--output", type=Path, default=ROOT / "core/generated/catalogue_data.h")
    args = parser.parse_args()
    generate(args.source, args.output)
